// The params of a shape of land made by code (defineGenerator), under the field that names it
function ShapeParams({ shape, values, onChange }: { shape: string; values?: Params; onChange: (values: Params) => void }) {
    const store = useSceneStore();
    const defs: Record<string, ParamDef> | undefined = store.registry.getGenerator(shape)?.params;
    if (!defs || Object.keys(defs).length === 0) return null;
    return <Fields defs={defs} values={{ ...paramDefaults(defs), ...values }} onChange={(key, value) => onChange({ ...values, [key]: value } as Params)} />;
}

// The biome a terrain names, edited where it is used: the shape and the paint of the land, and what grows
// on it. The ground changes only when it is generated again.
export function BiomeEditor({ name, biome }: { name: string; biome: BiomeData }) {
    const props = biome.props ?? [];
    const setProps = (next: BiomeData["props"]) => updateBiome(name, { ...biome, props: next });
    return (
        <>
            <div className="terrain-heading" title={`biomes/${name}.json: every terrain that names this biome is generated by it`}>Biome: {name}</div>
            <Fields defs={biomeFields} values={{ ...defaultBiome, ...biome } as unknown as Params} onChange={(key, value) => updateBiome(name, { ...biome, [key]: value })} />
            <ShapeParams shape={biome.shape ?? ""} values={biome.shapeParams} onChange={(shapeParams) => updateBiome(name, { ...biome, shapeParams })} />
            {props.map((prop, n) => (
                <div key={n} className="terrain-props">
                    <div className="terrain-props-title">
                        Props {n + 1}
                        <span className="spacer" />
                        <button className="btn ghost" title="Remove this kind of props from the biome" onClick={() => setProps(props.filter((_, i) => i !== n))}>×</button>
                    </div>
                    <Fields
                        defs={biomePropFields}
                        values={{ ...defaultBiomeProp, ...prop } as unknown as Params}
                        onChange={(key, value) => setProps(props.map((old, i) => (i === n ? { ...old, [key]: value } : old)))}
                    />
                </div>
            ))}
            <div className="field">
                <label />
                <div className="control">
                    <button className="btn" title="One more kind of props that grows on this land: a prefab, how thick, how big, where" onClick={() => setProps([...props, { prefab: "" }])}>
                        Add Props
                    </button>
                </div>
            </div>
        </>
    );
}

// The names of the sides of a piece, as in PIECE_SIDES
const SIDE_NAMES: Record<string, string> = { "1,0": "+X", "-1,0": "−X", "0,1": "+Z", "0,-1": "−Z" };

// What the World component shows in the Inspector under its fields: its pieces, the piece the brush was over
// last with the tools of a terrain for it, new pieces beside it, Generate for the whole world
export function WorldTools({ entity, component }: { entity: EntityData; component: ComponentData }) {
    const store = useSceneStore();
    const [size, setSize] = useState(250);
    if (store.playing) return null;
    const world = (component.world as string | undefined) ?? "";
    const pieces = worldPieces(store.registry.terrainNames(), world);
    if (pieces.length === 0) {
        return (
            <div className="field">
                <label title="Meters along each side of a piece (at most 500)">Piece Size</label>
                <div className="control">
                    <NumberInput value={size} step={50} min={16} max={MAX_PIECE} onChange={setSize} />
                    <button className="btn" title={`Makes the first piece of the world: terrains/${pieceName(world || "World", 0, 0)}.json, level ground`} onClick={() => createWorldPiece(entity.id, size)}>
                        New World
                    </button>
                </div>
            </div>
        );
    }
    const target = store.terrainTarget;
    const piece = target && target.id === entity.id ? parsePiece(target.name) : null;
    const shown = store.worldMarker(entity.id)?.shown.size ?? 0;
    const free = piece ? PIECE_SIDES.filter(([di, dj]) => !store.registry.getTerrain(pieceName(world, piece.i + di, piece.j + dj))) : [];
    return (
        <>
            <div className="terrain-note" title="A piece is a file of terrains/ named <world>_<column>_<row>; only the pieces within Distance of the camera are shown">
                {pieces.length} piece(s) of {pieceSize(store.registry, pieces)} m, {shown} shown now.
            </div>
            <div className="field">
                <label />
                <div className="control">
                    <button className="btn primary" title="Makes every piece anew by its own settings of Generate; the edges of neighbors are made to meet. Ctrl+Z takes it back" onClick={() => generateWorld(entity.id)}>
                        Generate World
                    </button>
                </div>
            </div>
            {piece && target && (
                <>
                    <div className="terrain-heading" title={`terrains/${target.name}.json: the piece the brush was over last`}>Piece: {target.name}</div>
                    {free.length > 0 && (
                        <div className="field">
                            <label title="A new piece beside this one: its heights go on from the edges of its neighbors">Add Piece</label>
                            <div className="control">
                                {free.map(([di, dj]) => (
                                    <button key={`${di},${dj}`} className="btn" title={`terrains/${pieceName(world, piece.i + di, piece.j + dj)}.json`} onClick={() => createPiece(entity.id, piece.i + di, piece.j + dj)}>
                                        {SIDE_NAMES[`${di},${dj}`]}
                                    </button>
                                ))}
                            </div>
                        </div>
                    )}
                    <TerrainTools entity={entity} component={{ ...component, terrain: target.name }} piece />
                </>
            )}
            {!piece && <div className="terrain-note">No piece is near the camera: fly to the world, or raise Distance.</div>}
        </>
    );
}

// What the Terrain component shows in the Inspector under its fields: making the terrain asset, its size,
// generating its ground, and, while "Edit Terrain" is on, the brush. `piece`: the terrain is a piece of a World
// (its size is that of the world, Generate makes its edges meet the neighbors)
export function TerrainTools({ entity, component, piece = false }: { entity: EntityData; component: ComponentData; piece?: boolean }) {
    const store = useSceneStore();
    const name = (component.terrain as string | undefined) ?? "";
    const data = store.registry.getTerrain(name);
    // The size being typed, until Resize is pressed: [meters along X, meters along Z, cell]
    const [typed, setTyped] = useState<{ of: string; size: [number, number, number] } | null>(null);

    if (store.playing) return null;
    if (!data) {
        return (
            <div className="field">
                <label />
                <div className="control">
                    <button className="btn" title="Makes a terrain file (level ground 64 x 64 m) and puts it on this object" onClick={() => createTerrainAsset(entity.id)}>
                        New Terrain
                    </button>
                </div>
            </div>
        );
    }

    const [width, depth] = terrainSize(data);
    const size = typed?.of === name ? typed.size : [width, depth, data.cell] as [number, number, number];
    const setSize = (index: number, value: number) => setTyped({ of: name, size: size.map((old, i) => (i === index ? value : old)) as [number, number, number] });
    const resized = size[0] !== width || size[1] !== depth || size[2] !== data.cell;
    const palette = data.palette?.length ? data.palette : DEFAULT_PALETTE;
    // Where the terrain stands: a height the generator gives depends on the place in the world
    const place = () => store.terrainTarget?.mesh.getWorldPosition(new THREE.Vector3()) ?? new THREE.Vector3();
    const settings = generatorOf(data);
    const biome = settings.biome ? store.registry.getBiome(settings.biome) : undefined;
    const { brush } = store;
    const color = Math.min(brush.color, palette.length - 1);
    const rivers = data.rivers ?? [];
    const river = rivers[brush.river];
    // The point of that river that is picked, if it is still there
    const point = river?.points[brush.point];

    return (
        <>
            {!piece && <div className="field">
                <label title="Meters along X and along Z, and the meters between two heights">Size</label>
                <div className="control">
                    <NumberInput value={size[0]} step={1} min={1} onChange={(value) => setSize(0, value)} />
                    <NumberInput value={size[1]} step={1} min={1} onChange={(value) => setSize(1, value)} />
                    <NumberInput value={size[2]} step={0.25} min={0.1} onChange={(value) => setSize(2, value)} />
                </div>
            </div>}
            {resized && !piece && (
                <div className="field">
                    <label />
                    <div className="control">
                        <button
                            className="btn primary"
                            title="The ground keeps its shape; what is added around it goes on from its edge, what does not fit is cut off"
                            onClick={() => {
                                resizeTerrainAsset(name, size[0], size[1], size[2]);
                                setTyped(null);
                            }}
                        >
                            Resize to {Math.max(1, Math.round(size[0] / size[2])) * size[2]} x {Math.max(1, Math.round(size[1] / size[2])) * size[2]} m
                        </button>
                        <button className="btn ghost" onClick={() => setTyped(null)}>Cancel</button>
                    </div>
                </div>
            )}

            <div className="terrain-heading" title="Hills out of noise. The settings are kept in the file of the terrain">Generate</div>
            <Fields defs={generatorFields} values={settings as unknown as Params} onChange={(key, value) => setTerrainGenerator(name, { [key]: value as number | boolean | string })} />
            {!settings.biome && <ShapeParams shape={settings.shape} values={settings.shapeParams} onChange={(shapeParams) => setTerrainGenerator(name, { shapeParams })} />}
            {!settings.biome && (
                <div className="field">
                    <label />
                    <div className="control">
                        <button className="btn" title="Makes a biome file (a kind of land: its shape, its paint, its props) and puts it on this terrain" onClick={() => createBiome(name)}>
                            New Biome
                        </button>
                    </div>
                </div>
            )}
            {biome && <BiomeEditor name={settings.biome} biome={biome} />}
            <div className="field">
                <label />
                <div className="control">
                    <button
                        className="btn primary"
                        title={data.biomeMap
                            ? "Makes the ground anew by the biomes that lie on it: every part by its own biome. Ground that no biome has made stays as it is. Ctrl+Z takes it back"
                            : "Makes the whole ground anew by these settings: what was shaped, painted and (with a biome) planted by hand is replaced. Ctrl+Z takes it back"}
                        onClick={() => (piece ? generateWorld(entity.id, [name]) : generateTerrainAsset(name, place()))}
                    >
                        Generate
                    </button>
                    {data.biomeMap && biome && (
                        <button className="btn" title={`Makes all of the ground ${settings.biome}, whatever biomes lay on it`} onClick={() => (piece ? generateWorld(entity.id, [name], true) : generateTerrainAsset(name, place(), true))}>
                            Fill
                        </button>
                    )}
                    <button
                        className="btn"
                        title="Another seed, and the ground made by it"
                        onClick={() => {
                            setTerrainGenerator(name, { seed: Math.floor(Math.random() * 100000) });
                            if (piece) generateWorld(entity.id, [name]);
                            else generateTerrainAsset(name, place());
                        }}
                    >
                        New Seed
                    </button>
                </div>
            </div>

            {data.biomeMap && (
                <>
                    <div className="terrain-note" title="Which biome was laid where is kept in the file of the terrain. The Generate brush lays the biome picked above with its land, the Biome brush only marks the ground">
                        On this ground:{" "}
                        {[...biomeShares(data)].sort((a, b) => b[1] - a[1]).map(([land, count], n) => (
                            <span key={land}>
                                {n > 0 && ", "}
                                {land && <span className="terrain-chip" style={{ background: biomeColor(data.biomes?.indexOf(land) ?? 0) }} />}
                                {land || "no biome"} {Math.round((count / (data.heights.length * data.heights[0].length)) * 100)}%
                            </span>
                        ))}
                    </div>
                    <div className="field">
                        <label />
                        <div className="control">
                            <button className={`btn ghost ${store.biomeView ? "active" : ""}`} title="Shows in the viewport which biome lies where: every biome in its color over the ground" onClick={() => store.setBiomeView(!store.biomeView)}>
                                Show Biomes
                            </button>
                        </div>
                    </div>
                </>
            )}

            {store.terrainEdit && (
                <>
                    <div className="terrain-tools">
                        {TOOLS.map(({ tool, label, title }) => (
                            <button key={tool} className={`btn ghost ${brush.tool === tool ? "active" : ""}`} title={title} onClick={() => store.setBrush({ tool })}>
                                {label}
                            </button>
                        ))}
                    </div>
                    {brush.tool !== "river" && <div className="field">
                        <label title="Meters">Radius</label>
                        <div className="control">
                            <NumberInput value={brush.radius} step={0.5} min={0.25} max={200} onChange={(radius) => store.setBrush({ radius })} />
                        </div>
                    </div>}
                    {(brush.tool === "plant" || brush.tool === "erase") && (
                        <>
                            {brush.tool === "plant" && (
                                <>
                                    <div className="field">
                                        <label title="The prefab whose copies are planted. A copy is what the prefab looks like and the solid Collider of its root; its behaviors, lights and sounds are not there">Prefab</label>
                                        <div className="control">
                                            <select className="select" value={brush.prefab} onChange={(e) => store.setBrush({ prefab: e.target.value })}>
                                                <option value="">(none)</option>
                                                {store.registry.prefabNames().map((prefab) => (
                                                    <option key={prefab} value={prefab}>{prefab}</option>
                                                ))}
                                            </select>
                                        </div>
                                    </div>
                                    <div className="field">
                                        <label title="Copies of the prefab are no nearer to each other than this, meters">Spacing</label>
                                        <div className="control">
                                            <NumberInput value={brush.spacing} step={0.5} min={0.1} max={100} onChange={(spacing) => store.setBrush({ spacing })} />
                                        </div>
                                    </div>
                                    <div className="field">
                                        <label title="Each copy is from so many to so many times the size of the prefab">Size</label>
                                        <div className="control">
                                            <NumberInput value={brush.sizeMin} step={0.1} min={0.01} onChange={(sizeMin) => store.setBrush({ sizeMin, sizeMax: Math.max(sizeMin, brush.sizeMax) })} />
                                            <NumberInput value={brush.sizeMax} step={0.1} min={0.01} onChange={(sizeMax) => store.setBrush({ sizeMax, sizeMin: Math.min(sizeMax, brush.sizeMin) })} />
                                        </div>
                                    </div>
                                </>
                            )}
                            <div className="terrain-note">
                                {scatterCount(data)} props on this terrain{(data.scatter ?? []).map((layer) => `, ${layer.prefab}: ${layer.items.length}`).join("")}
                            </div>
                        </>
                    )}
                    {brush.tool === "biome" && (
                        <div className="terrain-note">
                            {settings.biome ? `Marks the ground as ${settings.biome}; with Shift, as no one's.` : "No biome is picked in Generate: the brush makes the ground no one's."} Press Generate to make the ground by the map.
                        </div>
                    )}
                    {brush.tool === "river" && (
                        <>
                            <div className="field">
                                <label title="The river the clicks add points to">River</label>
                                <div className="control">
                                    <select className="select" value={Math.min(brush.river, rivers.length)} onChange={(e) => store.setBrush({ river: Number(e.target.value), point: -1 })}>
                                        {rivers.map((each, n) => (
                                            <option key={n} value={n}>River {n + 1} ({each.points.length} points)</option>
                                        ))}
                                        <option value={rivers.length}>(new river)</option>
                                    </select>
                                </div>
                            </div>
                            {river && (
                                <>
                                    <Fields
                                        defs={riverFields}
                                        values={{ ...defaultRiver, ...river } as unknown as Params}
                                        onChange={(key, value) => editRivers(name, (list) => {
                                            list[brush.river] = { ...list[brush.river], [key]: value };
                                        })}
                                    />
                                    {point && (
                                        <div className="field">
                                            <label title="The picked point (click its mark in the viewport): meters from the middle of the terrain along X and along Z, and how high the water is there. Water does not run uphill: a point higher than the one before it counts as level with it">Point {brush.point + 1}</label>
                                            <div className="control">
                                                {point.map((value, axis) => (
                                                    <NumberInput
                                                        key={axis}
                                                        value={value}
                                                        step={axis === 2 ? 0.1 : 1}
                                                        onChange={(next) => editRivers(name, (list) => {
                                                            list[brush.river].points[brush.point][axis] = Math.round(next * 100) / 100;
                                                        })}
                                                    />
                                                ))}
                                            </div>
                                        </div>
                                    )}
                                    <div className="field">
                                        <label />
                                        <div className="control">
                                            <button
                                                className="btn"
                                                title="Takes the picked point of the river away (the last one, if none is picked). The bed that was cut to it stays in the ground"
                                                onClick={() => {
                                                    editRivers(name, (list) => void list[brush.river].points.splice(point ? brush.point : -1, 1));
                                                    store.setBrush({ point: -1 });
                                                }}
                                            >
                                                Remove Point
                                            </button>
                                            <button
                                                className="btn"
                                                title="Takes the river away. Its bed stays in the ground: smooth it by hand, or generate the ground again"
                                                onClick={() => {
                                                    editRivers(name, (list) => void list.splice(brush.river, 1));
                                                    store.setBrush({ point: -1 });
                                                }}
                                            >
                                                Delete River
                                            </button>
                                        </div>
                                    </div>
                                </>
                            )}
                            <div className="terrain-note">
                                Click on the ground, from the spring down to the mouth: the water is a little under the ground at each point and never runs uphill, so through a hill the river cuts a gorge. Ctrl + click puts a point into the line; drag a mark to move its point. The bed a river has left stays in the ground: the Generate brush or Smooth heals it.
                            </div>
                        </>
                    )}
                    {brush.tool !== "paint" && brush.tool !== "erase" && brush.tool !== "biome" && brush.tool !== "river" && (
                        <div className="field">
                            <label title="Raise and Lower: meters per second in the middle of the brush. Smooth, Flatten and Generate: how fast they work. Plant: how fast the props appear">Strength</label>
                            <div className="control">
                                <NumberInput value={brush.strength} step={0.5} min={0.1} max={100} onChange={(strength) => store.setBrush({ strength })} />
                            </div>
                        </div>
                    )}
                    {brush.tool === "paint" && (
                        <>
                            <div className="field">
                                <label title="The kinds of ground of this terrain. Click one to paint with it">Palette</label>
                                <div className="control terrain-palette">
                                    {palette.map((swatch, i) => (
                                        <button
                                            key={i}
                                            className={`terrain-swatch ${i === color ? "active" : ""}`}
                                            style={{ background: swatch }}
                                            title={`${i}: ${swatch}`}
                                            onClick={() => store.setBrush({ color: i })}
                                        />
                                    ))}
                                    {palette.length < MAX_TERRAIN_COLORS && (
                                        <button
                                            className="btn ghost"
                                            title="One more color"
                                            onClick={() => {
                                                setTerrainPalette(name, [...palette, "#b0a070"]);
                                                store.setBrush({ color: palette.length });
                                            }}
                                        >
                                            +
                                        </button>
                                    )}
                                    {palette.length > 1 && (
                                        <button
                                            className="btn ghost"
                                            title="Remove the last color; what was painted with it gets the first one"
                                            onClick={() => {
                                                setTerrainPalette(name, palette.slice(0, -1));
                                                store.setBrush({ color: Math.min(color, palette.length - 2) });
                                            }}
                                        >
                                            −
                                        </button>
                                    )}
                                </div>
                            </div>
                            <div className="field">
                                <label title="The color of the kind of ground that is picked: changing it repaints all the ground of that kind">Color</label>
                                <div className="control">
                                    <input
                                        className="color-swatch"
                                        type="color"
                                        value={palette[color]}
                                        onChange={(e) => setTerrainPalette(name, palette.map((old, i) => (i === color ? e.target.value : old)))}
                                    />
                                    <span className="terrain-note">{palette[color]}</span>
                                </div>
                            </div>
                            {!isPainted(data) && <div className="terrain-note">Not painted yet: the first stroke paints all of it with the first color. The colors are multiplied by the material — use a white one, or none.</div>}
                        </>
                    )}
                    <div className="terrain-note">{brush.tool === "river" ? "Click on the ground." : "Hold the left button on the ground."} The camera: right button and W A S D, the wheel.</div>
                </>
            )}
        </>
    );
}
